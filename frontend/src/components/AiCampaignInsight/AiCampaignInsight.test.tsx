import { render, screen, within } from "@testing-library/react";

import type { AdInsights } from "../../types/api";
import { AiCampaignInsight } from "./AiCampaignInsight";

const content = {
  summary: "The ad performs above the campaign benchmark.",
  strengths: ["CTR is above the campaign benchmark."],
  risks: ["Meta CTR is below the campaign benchmark."],
  recommended_next_experiment: "Test clearer ad copy on Meta.",
  hypothesis: "Clearer copy will improve Meta CTR.",
  metrics_to_measure: ["CTR on Meta", "Engagement rate on Meta"],
};

const demoInsight = { ...content, provider: "demo", model: null } satisfies AdInsights;
const liveInsight = {
  ...content,
  provider: "openai",
  model: "gpt-4o-mini",
} satisfies AdInsights;

describe("AiCampaignInsight", () => {
  it("renders the insight and the recommended experiment in separate sections", () => {
    render(<AiCampaignInsight insight={demoInsight} />);

    const insightSection = screen.getByRole("region", { name: "Insight" });
    const experimentSection = screen.getByRole("region", {
      name: "Recommended next experiment",
    });

    expect(
      within(insightSection).getByText("The ad performs above the campaign benchmark."),
    ).toBeInTheDocument();
    expect(
      within(insightSection).getByText("CTR is above the campaign benchmark."),
    ).toBeInTheDocument();
    expect(
      within(insightSection).getByText("Meta CTR is below the campaign benchmark."),
    ).toBeInTheDocument();

    expect(
      within(experimentSection).getByText("Test clearer ad copy on Meta."),
    ).toBeInTheDocument();
    expect(
      within(experimentSection).getByText("Clearer copy will improve Meta CTR."),
    ).toBeInTheDocument();
    expect(within(experimentSection).getByText("CTR on Meta")).toBeInTheDocument();
    expect(
      within(experimentSection).getByText("Engagement rate on Meta"),
    ).toBeInTheDocument();
  });

  it("clearly marks demo output as not generated by a language model", () => {
    render(<AiCampaignInsight insight={demoInsight} />);

    expect(screen.getByText("Demo AI · Sample insights")).toBeInTheDocument();
    expect(screen.getByText(/No language model was used/)).toBeInTheDocument();
  });

  it("attributes live output to the model that produced it", () => {
    render(<AiCampaignInsight insight={liveInsight} />);

    expect(screen.getByText("Live AI · gpt-4o-mini")).toBeInTheDocument();
    expect(screen.getByText(/Generated by gpt-4o-mini/)).toBeInTheDocument();
    expect(screen.queryByText(/Demo AI/)).not.toBeInTheDocument();
  });

  it("shows placeholders for empty lists", () => {
    render(
      <AiCampaignInsight insight={{ ...demoInsight, strengths: [], risks: [] }} />,
    );

    expect(
      screen.getByText("No clear strengths in the available data."),
    ).toBeInTheDocument();
    expect(screen.getByText("No risks identified.")).toBeInTheDocument();
  });
});

import type { AdInsights } from "../../types/api";
import { ProviderBadge } from "../ProviderBadge/ProviderBadge";

import "./AiCampaignInsight.scss";

type AiCampaignInsightProps = {
  insight: AdInsights;
};

const InsightList = ({ items, empty }: { items: string[]; empty: string }) =>
  items.length === 0 ? (
    <p className="ai-campaign-insight__empty">{empty}</p>
  ) : (
    <ul>
      {items.map((item) => (
        <li key={item}>{item}</li>
      ))}
    </ul>
  );

export const AiCampaignInsight = ({ insight }: AiCampaignInsightProps) => {
  return (
    <section
      className="ai-campaign-insight"
      aria-labelledby="ai-campaign-insight-heading"
    >
      <header className="ai-campaign-insight__header">
        <h2 id="ai-campaign-insight-heading">Insights for this ad</h2>
        <ProviderBadge provider={insight.provider} model={insight.model} />
      </header>

      <p className="ai-campaign-insight__notice">
        {insight.provider === "demo"
          ? "Sample insight produced by AdPulse's rule-based demo engine from this ad's metrics. No language model was used."
          : `Generated by ${insight.model ?? "a language model"} from this ad's metrics. Review before acting.`}
      </p>

      <div className="ai-campaign-insight__sections">
        <section
          className="ai-campaign-insight__panel"
          aria-labelledby="ai-insight-summary-heading"
        >
          <h3 id="ai-insight-summary-heading" className="ai-campaign-insight__label">
            Insight
          </h3>

          <p className="ai-campaign-insight__summary">{insight.summary}</p>

          <div className="ai-campaign-insight__columns">
            <div>
              <h4 className="ai-campaign-insight__sublabel">What&apos;s working</h4>
              <InsightList
                items={insight.strengths}
                empty="No clear strengths in the available data."
              />
            </div>

            <div>
              <h4 className="ai-campaign-insight__sublabel">Watch</h4>
              <InsightList items={insight.risks} empty="No risks identified." />
            </div>
          </div>
        </section>

        <section
          className="ai-campaign-insight__panel ai-campaign-insight__experiment"
          aria-labelledby="ai-insight-experiment-heading"
        >
          <h3
            id="ai-insight-experiment-heading"
            className="ai-campaign-insight__label"
          >
            Recommended next experiment
          </h3>

          <p className="ai-campaign-insight__experiment-text">
            {insight.recommended_next_experiment}
          </p>

          <div className="ai-campaign-insight__experiment-grid">
            <div>
              <h4 className="ai-campaign-insight__sublabel">Hypothesis</h4>
              <p>{insight.hypothesis}</p>
            </div>

            <div>
              <h4 className="ai-campaign-insight__sublabel">Measure</h4>
              <InsightList
                items={insight.metrics_to_measure}
                empty="No metrics specified."
              />
            </div>
          </div>
        </section>
      </div>
    </section>
  );
};

import type { InsightProvider } from "../../types/api";

import "./ProviderBadge.scss";

type ProviderBadgeProps = {
  provider: InsightProvider;
  model?: string | null;
};

export const ProviderBadge = ({ provider, model }: ProviderBadgeProps) => {
  if (provider === "demo") {
    return (
      <span
        className="provider-badge provider-badge--demo"
        title="Produced by deterministic rules from this ad's metrics. No language model is used."
      >
        Demo AI · Sample insights
      </span>
    );
  }

  return (
    <span
      className="provider-badge provider-badge--live"
      title="Generated by a large language model. Review before acting."
    >
      Live AI{model ? ` · ${model}` : ""}
    </span>
  );
};
